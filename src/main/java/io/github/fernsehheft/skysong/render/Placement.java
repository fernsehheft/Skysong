package io.github.fernsehheft.skysong.render;

/** Where a new line of lyrics shows up. */
public enum Placement {
    /** Straight ahead, where you were looking when the line started. */
    AHEAD,
    /** Somewhere around you, a different spot for every line. */
    SCATTERED,
    /** Big and far away, high up in the sky in front of you. */
    SKY
}
